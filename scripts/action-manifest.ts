// The action manifest (services/runner/code/internal/power/actions.manifest.json):
// the app's action registry (packages/surfaces/src/actions.ts) and its keymap
// presets, as data the Runner and the `lazybox` CLI read. `lazybox do --list`
// prints it; the Runner checks keys.yaml, `do:` steps and layout files against
// it, and lets a hook run only the actions it marks safe (POWER.md).
//
//   npm run generate:manifest     regenerate it
//   npm run test:client           fails when the committed manifest is stale
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { actionDefinitions, type ActionDefinition } from '../packages/surfaces/src/actions';
import { keyboardPreset } from '../packages/surfaces/src/keyboard';
import { builtinPresets, layoutPanelKinds } from '../packages/surfaces/src/layout-presets';

export const manifestPath = fileURLToPath(new URL('../services/runner/code/internal/power/actions.manifest.json', import.meta.url));
export const presetNames = ['vim', 'tmux', 'arrows'] as const;

export function renderManifest(): string {
  const actions = actionDefinitions.map((definition: ActionDefinition) => {
    const out: Record<string, unknown> = { id: definition.id, title: definition.title, group: definition.group, scope: definition.scope, keys: definition.keys };
    if (definition.otherKeys !== undefined) out.otherKeys = definition.otherKeys;
    for (const flag of ['required', 'fixed', 'hold', 'safe', 'destructive'] as const) if (definition[flag]) out[flag] = true;
    if (definition.argument) out.argument = definition.argument;
    return out;
  });
  const keymaps = Object.fromEntries((['mac', 'other'] as const).map(platform => [platform, Object.fromEntries(presetNames.map(preset => [preset, keyboardPreset(preset, platform === 'mac')]))]));
  const manifest = {
    $comment: 'GENERATED by scripts/action-manifest.ts from packages/surfaces/src/actions.ts — do not edit; run `npm run generate:manifest` in v2/.',
    version: 1,
    actions,
    presets: presetNames,
    keymaps,
    layoutPanels: layoutPanelKinds,
    builtinLayouts: builtinPresets.map(preset => ({ id: preset.id, name: preset.name })),
  };
  return JSON.stringify(manifest, null, 1) + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(manifestPath, renderManifest());
  console.log(`wrote ${manifestPath}`);
}
