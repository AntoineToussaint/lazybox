// Package agentshell keeps this Runner's `lazybox` first on PATH in every
// shell an agent, a managed command or a workspace terminal starts, whatever
// the person's shell startup files do to PATH.
//
// The Runner puts its CLI first on the PATH it gives a process. That is not
// enough: zsh reads ~/.zshenv for every shell, scripts included, and a
// `path=(~/.cargo/bin … $path)` there (or mise, Homebrew's shellenv, macOS's
// path_helper in /etc/zprofile for login shells) puts another lazybox (V1
// installs one) ahead of it. Claude Code and Codex run every command through
// the person's shell, so `lazybox run` would run that one.
//
// Three hooks, each read by a shell after the person's own files, put the CLI
// back first:
//
//   - zsh: ZDOTDIR points at a directory whose .zshenv, .zprofile, .zshrc,
//     .zlogin and .zlogout each source the person's own file (from their
//     ZDOTDIR, or HOME) with ZDOTDIR set as they had it, then move the CLI
//     to the front. Every zsh reads them, `-c`, `-lc` and interactive alike,
//     and nested ones too: ZDOTDIR stays exported. The same technique VS Code
//     and other terminals use for their shell integration.
//   - bash: BASH_ENV, which bash reads after its profile files for every
//     non-interactive shell (`bash -c` and `bash -lc`), chains the person's
//     own BASH_ENV and moves the CLI to the front.
//   - Claude Code: CLAUDE_ENV_FILE, a script Claude Code runs before each Bash
//     tool command, after its shell snapshot. It covers a snapshot that sets a
//     PATH without the CLI (a PATH in the person's Claude settings) and any
//     shell. The person's own CLAUDE_ENV_FILE is chained.
//
// LAZYBOX_V2_CLI names the CLI's absolute path, the fallback the agent
// briefing gives for a shell none of these reach. Probe checks, through the
// person's real shell, which lazybox each kind of shell finds.
package agentshell

import (
	"bytes"
	"errors"
	"os"
	"path/filepath"
	"strings"
)

// Variables this package sets. The *_USER_* ones carry the person's own value
// of a variable the integration replaces, so its files can chain to it.
const (
	EnvCLIDir   = "LAZYBOX_V2_CLI_DIR"
	EnvCLI      = "LAZYBOX_V2_CLI"
	EnvZDOTDIR  = "LAZYBOX_V2_ZDOTDIR"
	envUserZDOT = "LAZYBOX_V2_USER_ZDOTDIR"
	envUserBash = "LAZYBOX_V2_USER_BASH_ENV"
	envUserCC   = "LAZYBOX_V2_USER_CLAUDE_ENV_FILE"
)

// marker names the file that identifies an integration directory, so an
// integration inherited from another Lazybox (a Runner started from a
// Lazybox terminal) is recognised and never chained to itself.
const marker = ".lazybox-shell-integration"

const header = "# Lazybox shell integration. Generated by the Lazybox Runner; edits are replaced.\n"

// zshFile is one of the zsh startup files: it runs the person's own file of
// the same name with ZDOTDIR as they set it, keeps a ZDOTDIR their file sets,
// then points ZDOTDIR back here and puts the CLI first. It runs at top level,
// not in a function, so `typeset` and `local` in their file mean what they
// would without Lazybox.
func zshFile(name, before, after string) string {
	return header + `# zsh reads its startup files from $ZDOTDIR, which Lazybox points here. This
# file runs your own ` + name + ` unchanged, with ZDOTDIR as you set it, then puts
# Lazybox's CLI back first on PATH so ` + "`lazybox`" + ` is this Lazybox's.
` + before + `if [[ -n ${LAZYBOX_V2_USER_ZDOTDIR+set} ]]; then ZDOTDIR=$LAZYBOX_V2_USER_ZDOTDIR; else unset ZDOTDIR; fi
if [[ -f ${ZDOTDIR:-$HOME}/` + name + ` ]]; then source ${ZDOTDIR:-$HOME}/` + name + `; fi
if [[ -n ${ZDOTDIR+set} && $ZDOTDIR != "$LAZYBOX_V2_ZDOTDIR" ]]; then export LAZYBOX_V2_USER_ZDOTDIR=$ZDOTDIR; else unset LAZYBOX_V2_USER_ZDOTDIR; fi
if [[ -n ${LAZYBOX_V2_ZDOTDIR-} ]]; then export ZDOTDIR=$LAZYBOX_V2_ZDOTDIR; fi
if [[ -n ${LAZYBOX_V2_CLI_DIR-} ]]; then path=("$LAZYBOX_V2_CLI_DIR" ${path:#${(b)LAZYBOX_V2_CLI_DIR}}); export PATH; fi
` + after
}

// zshrcBefore undoes macOS's /etc/zshrc, which ran before this file and set
// HISTFILE from ZDOTDIR, so history stays where the person keeps it.
const zshrcBefore = `if [[ ${HISTFILE-} == "$LAZYBOX_V2_ZDOTDIR/.zsh_history" ]]; then HISTFILE=${LAZYBOX_V2_USER_ZDOTDIR:-$HOME}/.zsh_history; fi
`

// zshrcAfter covers prompt hooks: a tool that reorders PATH before each
// prompt (mise activate, direnv) does so after every startup file, so an
// interactive shell puts the CLI first once more, before its first prompt.
const zshrcAfter = `if [[ -o interactive && -n ${LAZYBOX_V2_CLI_DIR-} ]]; then
  _lazybox_cli_first() {
    path=("$LAZYBOX_V2_CLI_DIR" ${path:#${(b)LAZYBOX_V2_CLI_DIR}})
    precmd_functions=(${precmd_functions:#_lazybox_cli_first})
  }
  typeset -ga precmd_functions
  precmd_functions+=(_lazybox_cli_first)
fi
` + zshCommandEnd

// zshCommandEnd marks, in an interactive shell (a workspace terminal), where
// each command line ended and with what status: OSC 133;D;<status>, the
// semantic-prompt mark other terminals use. The window reads it to say that
// a command it typed for the person (Run in … home) finished, and how. It
// runs first among the prompt hooks so the status is the command's own; a
// terminal that does not know the mark ignores it.
const zshCommandEnd = `if [[ -o interactive ]]; then
  _lazybox_command_end() { local s=$?; print -rn -- $'\e]133;D;'$s$'\a'; return $s; }
  typeset -ga precmd_functions
  precmd_functions=(_lazybox_command_end ${precmd_functions:#_lazybox_command_end})
fi
`

// bashEnv is BASH_ENV: bash reads it after its profile files for every
// non-interactive shell. It is written for bash alone (bash 3.2, macOS's).
const bashEnv = header + `# bash reads $BASH_ENV, after your profile, for every script and ` + "`bash -c`" + `.
# This file runs your own BASH_ENV, then puts Lazybox's CLI back first on PATH.
if [ -n "${LAZYBOX_V2_USER_BASH_ENV-}" ] && [ -f "$LAZYBOX_V2_USER_BASH_ENV" ]; then . "$LAZYBOX_V2_USER_BASH_ENV"; fi
if [ -n "${LAZYBOX_V2_CLI_DIR-}" ]; then
  __lazybox_path=":${PATH-}:"
  while case $__lazybox_path in *":$LAZYBOX_V2_CLI_DIR:"*) true ;; *) false ;; esac; do
    __lazybox_path=${__lazybox_path/":$LAZYBOX_V2_CLI_DIR:"/:}
  done
  __lazybox_path=${__lazybox_path#:}
  __lazybox_path=${__lazybox_path%:}
  PATH=$LAZYBOX_V2_CLI_DIR${__lazybox_path:+:$__lazybox_path}
  export PATH
  unset __lazybox_path
fi
`

// claudeEnv is CLAUDE_ENV_FILE. Claude Code runs its text inside each Bash
// tool command, after the shell snapshot and before the command, in bash or
// zsh, so it is plain POSIX shell and never fails.
const claudeEnv = `if [ -n "${LAZYBOX_V2_USER_CLAUDE_ENV_FILE-}" ] && [ -f "$LAZYBOX_V2_USER_CLAUDE_ENV_FILE" ]; then . "$LAZYBOX_V2_USER_CLAUDE_ENV_FILE"; fi
if [ -n "${LAZYBOX_V2_CLI_DIR-}" ]; then PATH="$LAZYBOX_V2_CLI_DIR:${PATH-}"; export PATH; fi
`

// Files is every file of an integration directory, by its path inside it.
func Files() map[string]string {
	files := map[string]string{
		marker:                            "Lazybox shell integration: see internal/agentshell. Generated by the Lazybox Runner.\n",
		"bash-env.sh":                     bashEnv,
		"claude-env.sh":                   claudeEnv,
		filepath.Join("zsh", marker):      "",
		filepath.Join("zsh", ".zshenv"):   zshFile(".zshenv", "", ""),
		filepath.Join("zsh", ".zprofile"): zshFile(".zprofile", "", ""),
		filepath.Join("zsh", ".zshrc"):    zshFile(".zshrc", zshrcBefore, zshrcAfter),
		filepath.Join("zsh", ".zlogin"):   zshFile(".zlogin", "", ""),
	}
	// .zlogout runs the person's own and touches nothing else.
	files[filepath.Join("zsh", ".zlogout")] = header + `if [[ -n ${LAZYBOX_V2_USER_ZDOTDIR+set} ]]; then ZDOTDIR=$LAZYBOX_V2_USER_ZDOTDIR; else unset ZDOTDIR; fi
if [[ -f ${ZDOTDIR:-$HOME}/.zlogout ]]; then source ${ZDOTDIR:-$HOME}/.zlogout; fi
`
	return files
}

// Install writes the integration into dir, readable by the user alone. A file
// already holding the same text is left alone, so shells reading it while a
// Runner starts never see it missing.
func Install(dir string) error {
	if dir == "" || !filepath.IsAbs(dir) {
		return errors.New("shell integration directory must be absolute")
	}
	var failures []error
	for name, text := range Files() {
		path := filepath.Join(dir, name)
		if current, err := os.ReadFile(path); err == nil && bytes.Equal(current, []byte(text)) {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			failures = append(failures, err)
			continue
		}
		if err := writePrivate(path, []byte(text)); err != nil {
			failures = append(failures, err)
		}
	}
	return errors.Join(failures...)
}

// Env returns env with the CLI first on PATH and, when dir holds an installed
// integration, the variables that make every shell put it back there. The
// person's own ZDOTDIR, BASH_ENV and CLAUDE_ENV_FILE are kept for the
// integration's files to chain to. With no cliDir, env is returned unchanged.
func Env(env []string, dir, cliDir string) []string {
	if cliDir == "" {
		return env
	}
	values := map[string]string{}
	for _, entry := range env {
		if name, value, ok := strings.Cut(entry, "="); ok {
			values[name] = value
		}
	}
	// The person's value of a replaced variable. One that is an integration
	// itself (inherited from a Lazybox terminal or agent) stands for the
	// person's value it saved: in env, or in this process's environment when
	// env was stripped of LAZYBOX_V2_* (a Runner started from a Lazybox shell).
	user := func(name, saved string) (string, bool) {
		value, ok := values[name]
		if ok && isIntegration(value) {
			if value, ok = values[saved]; !ok {
				value, ok = os.LookupEnv(saved)
			}
			if ok && isIntegration(value) {
				value, ok = "", false
			}
		}
		return value, ok
	}
	zdotdir, hasZdotdir := user("ZDOTDIR", envUserZDOT)
	bashEnv, hasBashEnv := user("BASH_ENV", envUserBash)
	claudeEnv, hasClaudeEnv := user("CLAUDE_ENV_FILE", envUserCC)
	path, hasPath := values["PATH"]
	if !hasPath {
		path = os.Getenv("PATH")
	}
	replaced := map[string]bool{"PATH": true, "ZDOTDIR": true, "BASH_ENV": true, "CLAUDE_ENV_FILE": true, EnvCLIDir: true, EnvCLI: true, EnvZDOTDIR: true, envUserZDOT: true, envUserBash: true, envUserCC: true}
	out := make([]string, 0, len(env)+10)
	for _, entry := range env {
		name, _, _ := strings.Cut(entry, "=")
		if !replaced[name] {
			out = append(out, entry)
		}
	}
	out = append(out, "PATH="+First(path, cliDir), EnvCLIDir+"="+cliDir, EnvCLI+"="+filepath.Join(cliDir, "lazybox"))
	hooks := []struct {
		name, saved, value string
		has                bool
	}{{"ZDOTDIR", envUserZDOT, zdotdir, hasZdotdir}, {"BASH_ENV", envUserBash, bashEnv, hasBashEnv}, {"CLAUDE_ENV_FILE", envUserCC, claudeEnv, hasClaudeEnv}}
	integrated := dir != "" && isIntegration(dir)
	if integrated {
		zsh := filepath.Join(dir, "zsh")
		out = append(out, "ZDOTDIR="+zsh, EnvZDOTDIR+"="+zsh, "BASH_ENV="+filepath.Join(dir, "bash-env.sh"), "CLAUDE_ENV_FILE="+filepath.Join(dir, "claude-env.sh"))
	}
	for _, h := range hooks {
		switch {
		case !h.has:
		case integrated:
			out = append(out, h.saved+"="+h.value) // the integration chains to it
		default:
			out = append(out, h.name+"="+h.value) // no integration: the person's own, as it was
		}
	}
	return out
}

// First returns path with dir first and nowhere else.
func First(path, dir string) string {
	parts := []string{dir}
	for _, entry := range filepath.SplitList(path) {
		if entry != dir {
			parts = append(parts, entry)
		}
	}
	return strings.Join(parts, string(os.PathListSeparator))
}

// isIntegration reports whether path is an integration directory or a file in one.
func isIntegration(path string) bool {
	if path == "" || !filepath.IsAbs(path) {
		return false
	}
	for _, dir := range []string{path, filepath.Dir(path)} {
		if info, err := os.Stat(filepath.Join(dir, marker)); err == nil && info.Mode().IsRegular() {
			return true
		}
	}
	return false
}

// writePrivate replaces a file atomically, readable by the user alone.
func writePrivate(path string, data []byte) error {
	f, err := os.CreateTemp(filepath.Dir(path), ".write-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err = f.Write(data); err == nil {
		err = f.Sync()
	}
	if closeErr := f.Close(); err == nil {
		err = closeErr
	}
	if err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}
