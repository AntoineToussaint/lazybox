import { createServer } from 'vite';
import { chromium, expect } from '@playwright/test';
import { readFile, writeFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { createRunnerClient } from '../packages/client-core/src/index.ts';
import assert from 'node:assert/strict';

const endpointPath = process.env.LAZYBOX_V2_ENDPOINT;
if (!endpointPath) throw new Error('Set LAZYBOX_V2_ENDPOINT; start the real Codefly Runner before this test');
const endpoint = JSON.parse(await readFile(endpointPath, 'utf8'));
const api = createRunnerClient(endpoint.url, endpoint.token);
const unauthenticated = await fetch(endpoint.url + '/lazybox.bench.v1.RunnerService/Info', { method: 'POST', headers: { 'Content-Type': 'application/json', 'Connect-Protocol-Version': '1' }, body: '{}' });
assert.equal(unauthenticated.status, 401, 'Connect must enforce the same authority as gRPC');
const server = await createServer({ root: fileURLToPath(new URL('../apps/web', import.meta.url)), server: { host: '127.0.0.1', port: 0 } });
await server.listen();
const url = `http://127.0.0.1:${server.httpServer.address().port}/#token=${endpoint.token}`;
const directory = await mkdtemp(tmpdir() + '/lazybox-v2-browser-');
let browser;
const sessions = new Set();
try {
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1500, height: 1050 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  const denied = await context.newPage();
  await denied.goto(url.replace(endpoint.token, 'invalid-token'));
  await expect(denied.getByRole('alert')).toContainText('unauthenticated');
  await expect(denied.getByRole('button', { name: 'Start Claude ↗' })).toBeDisabled();
  await expect(denied.getByRole('button', { name: 'Retry connection' })).toBeVisible();
  await denied.close();
  await page.goto(url);
  await expect(page.getByRole('combobox', { name: 'Agent', exact: true })).toHaveValue('claude');
  await expect(page.getByLabel('Account profile')).toHaveValue('claude-default');
  await page.screenshot({ path: '.cache/agent-window-setup.png', fullPage: true });
  let opens = 0;
  page.on('request', request => { if (request.url().endsWith('/OpenSession')) opens++; });
  await page.getByLabel('Working directory').fill(directory);
  const claudeOpened = page.waitForResponse(response => response.url().endsWith('/OpenSession'));
  await page.getByRole('button', { name: 'Start Claude ↗' }).click();
  const claudeResponse = await claudeOpened;
  const claudeData = await claudeResponse.json();
  assert.equal(claudeResponse.status(), 200, JSON.stringify(claudeData));
  const claudeSession = claudeData.session.id; sessions.add(claudeSession);
  assert.equal(claudeData.session.profileId, 'claude-default');
  await expect(page.getByRole('heading', { name: 'Claude', exact: true })).toBeVisible();
  await expect(page.getByLabel('Message')).toBeEnabled();
  assert.equal(new URL(page.url()).searchParams.get('session'), claudeSession);
  // Exercise composer delivery without inference. The Go transport tests cover
  // actual server retention and provider delivery; only Apply is intercepted here.
  const submissions = [];
  let failNextSubmission = false;
  await page.route('**/lazybox.bench.v1.RunnerService/Apply', async route => {
    const body = route.request().postDataJSON(); submissions.push(body);
    if (failNextSubmission) {
      failNextSubmission = false;
      await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 'unavailable', message: 'fixture delivery failure' }) }); return;
    }
    await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ operationId: body.operationId, delivery: 'accepted' }) });
  });
  const composer = page.getByLabel('Message');
  await composer.fill('first line');
  await composer.press('Shift+Enter');
  await composer.pressSequentially('second line');
  await expect(composer).toHaveValue('first line\nsecond line');
  assert.equal(submissions.length, 0, 'Shift+Enter must not send');
  await composer.press('Enter');
  await expect.poll(() => submissions.length).toBe(1);
  assert.equal(submissions[0].message.text, 'first line\nsecond line');
  await expect(composer).toHaveValue('');
  await composer.press('Enter');
  assert.equal(submissions.length, 1, 'empty Enter must not send');
  await composer.fill('漢');
  await composer.evaluate(node => node.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', isComposing: true, bubbles: true })));
  await composer.evaluate(node => node.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', keyCode: 229, bubbles: true })));
  await expect(composer).toHaveValue('漢');
  assert.equal(submissions.length, 1, 'IME confirmation must not send');
  await composer.fill('');
  const textFile = { name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('source attachment bytes') };
  const pdfFile = { name: 'report.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7\nfixture') };
  const picker = page.getByLabel('Attach files', { exact: true });
  assert.equal(await picker.getAttribute('accept'), null, 'generic picker must not filter to images');
  await picker.setInputFiles([textFile, pdfFile]);
  await expect(page.getByRole('list', { name: 'Attached files' })).toContainText('notes.txt');
  await expect(page.getByRole('list', { name: 'Attached files' })).toContainText('report.pdf');
  await page.getByRole('button', { name: 'Remove notes.txt', exact: true }).click();
  await picker.setInputFiles([textFile]);
  const sameNameFile = { ...textFile, buffer: Buffer.alloc(textFile.buffer.length, 'b') };
  await picker.setInputFiles([sameNameFile]);
  failNextSubmission = true;
  await composer.press('Enter');
  await expect.poll(() => submissions.length).toBe(2);
  await expect(page.getByRole('alert')).toContainText('fixture delivery failure');
  await expect(page.getByRole('list', { name: 'Attached files' })).toContainText('notes.txt');
  await expect(composer).toBeEnabled();
  await composer.press('Enter');
  await expect.poll(() => submissions.length).toBe(3);
  assert.equal(submissions[2].operationId, submissions[1].operationId, 'unchanged retry must preserve operation identity');
  const sentFiles = submissions[2].message.attachments;
  assert.equal(sentFiles.length, 3);
  assert.deepEqual(sentFiles.filter(file => file.name === 'notes.txt').map(file => Buffer.from(file.data, 'base64').toString()), [textFile.buffer.toString(), sameNameFile.buffer.toString()], 'same-named files must retain their distinct bytes');
  assert.equal(Buffer.from(sentFiles.find(file => file.name === 'report.pdf').data, 'base64').toString(), pdfFile.buffer.toString());
  await expect(page.getByRole('list', { name: 'Attached files' })).toHaveCount(0);
  const draftPath = directory + '/draft.txt';
  await writeFile(draftPath, 'draft attachment');
  await composer.fill('unsent follow-up');
  await picker.setInputFiles(draftPath);
  failNextSubmission = true;
  await composer.press('Enter');
  await expect.poll(() => submissions.length).toBe(4);
  await expect(page.getByRole('alert')).toContainText('fixture delivery failure');
  await page.reload();
  await expect(composer).toHaveValue('unsent follow-up');
  await expect(page.getByText('Reattach or remove these files before sending:')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Send message', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: '+ Attach files', exact: true })).toBeEnabled();
  await picker.setInputFiles(draftPath);
  await expect(page.getByText('Reattach or remove these files before sending:')).toHaveCount(0);
  await composer.press('Enter');
  await expect.poll(() => submissions.length).toBe(5);
  assert.equal(submissions[4].operationId, submissions[3].operationId, 'reopening an uncertain send must retain its operation identity');
  await expect(composer).toHaveValue('');
  await page.unroute('**/lazybox.bench.v1.RunnerService/Apply');
  if (process.env.LAZYBOX_V2_REAL === '1') {
    await page.getByLabel('Message').fill('Reply exactly LAZYBOX_CLAUDE_WINDOW_OK. Do not use tools.');
    await page.getByRole('button', { name: 'Send message', exact: true }).click();
    await expect(page.locator('.message.message_delta')).toContainText('LAZYBOX_CLAUDE_WINDOW_OK', { timeout: 120_000 });
  }
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Claude', exact: true })).toBeVisible();
  await expect(page.getByLabel('Message')).toBeEnabled();
  if (process.env.LAZYBOX_V2_REAL === '1') await expect(page.locator('.message.message_delta')).toContainText('LAZYBOX_CLAUDE_WINDOW_OK');
  assert.equal(opens, 1, 'StrictMode and reload must attach rather than spawn another session');
  await page.screenshot({ path: '.cache/agent-window-claude.png', fullPage: true });
  await page.getByRole('button', { name: 'End session', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Session ended');
  await page.getByRole('button', { name: 'New conversation', exact: true }).click();
  assert.equal(new URL(page.url()).searchParams.has('session'), false);
  await page.getByRole('combobox', { name: 'Agent', exact: true }).selectOption('codex');
  await page.getByLabel('Account profile').selectOption('codex-default');
  await page.getByLabel('Working directory').fill(directory);
  const opened = page.waitForResponse(response => response.url().endsWith('/OpenSession'));
  await page.getByRole('button', { name: 'Start Codex ↗' }).click();
  const response = await opened;
  const data = await response.json();
  assert.equal(response.status(), 200, JSON.stringify(data)); sessions.add(data.session.id);
  await page.getByText('Commands & output', { exact: false }).click();
  await page.getByLabel('Shell command').fill("printf 'started\\n' >> starts; printf 'first\\n'; while [ ! -f gate ]; do sleep 0.1; done; printf 'second\\n'");
  await page.getByRole('button', { name: 'Run', exact: true }).click();
  await expect(page.getByTestId('console-output')).toContainText('first');
  await page.getByLabel('Search output').fill('first');
  await page.getByLabel('Follow', { exact: true }).uncheck();
  const nextPage = context.waitForEvent('page');
  await page.getByRole('button', { name: 'Open viewer ↗' }).click();
  const viewer = await nextPage;
  await expect(viewer.getByTestId('console-output')).toContainText('first');
  await expect(viewer.getByLabel('Search output')).toHaveValue('');
  await expect(viewer.getByLabel('Follow', { exact: true })).toBeChecked();
  await page.close();
  await writeFile(directory + '/gate', 'continue');
  await expect(viewer.getByTestId('console-output')).toContainText('second');
  assert.equal(await viewer.getByTestId('console-output').textContent(), 'first\nsecond\n');
  await viewer.getByLabel('Search output').fill('second');
  await viewer.getByLabel('Follow', { exact: true }).uncheck();
  await viewer.reload();
  await expect(viewer.getByTestId('console-output')).toContainText('second');
  await expect(viewer.getByLabel('Search output')).toHaveValue('second');
  await expect(viewer.getByLabel('Follow', { exact: true })).not.toBeChecked();
  await viewer.getByLabel('Search output').fill('');
  assert.equal(await viewer.getByTestId('console-output').textContent(), 'first\nsecond\n');
  assert.equal(await readFile(directory + '/starts', 'utf8'), 'started\n');
  assert.deepEqual(errors, []);
  await viewer.screenshot({ path: '.cache/console-viewer.png', fullPage: true });
  console.log('PASS: authentication failure, Claude SDK session, Enter send / Shift+Enter newline / IME guard, generic multi-file picker and exact payload bytes (Apply intercepted), reload without duplicate spawn, explicit session end, Codex selection, independent command viewers, producer survives close, exact replay, command ran once.' + (process.env.LAZYBOX_V2_REAL === '1' ? ' Real Claude reply and transcript replay verified.' : ' No model inference requested.'));
} finally {
  for (const session of sessions) {
    for (const command of (await api.listCommands({ sessionId: session })).commands) if (!command.done) await api.cancelCommand({ commandId: command.id });
    await api.closeSession({ sessionId: session });
  }
  await browser?.close(); await server.close(); await rm(directory, { recursive: true, force: true });
}
